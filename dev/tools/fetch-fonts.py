"""Download Inter + Anuphan (SIL OFL) from Google Fonts for self-hosting.

The owner chose these fonts and allowed the download on 29 Oct 2026. Output:
  eabull/assets/fonts/<family>-<subset>.woff2  (variable weight files)
  eabull/assets/css/fonts.css                  (@font-face with unicode-range)
infra.php switches from Google Fonts to fonts.css once every file listed in
eab_infra_font_files() exists, so keep that list in sync with FILES below.
Usage: py -3 -I dev/tools/fetch-fonts.py
"""
import re
import sys
import urllib.request
from pathlib import Path

sys.stdout.reconfigure(encoding='utf-8')

THEME = Path(__file__).resolve().parents[2] / 'eabull'
FONTS = THEME / 'assets' / 'fonts'
CSS = THEME / 'assets' / 'css' / 'fonts.css'
API = 'https://fonts.googleapis.com/css2?family=Anuphan:wght@400;500;600;700&family=Inter:wght@400;500;600;700&display=swap'
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36'
KEEP = {('Anuphan', 'thai'), ('Anuphan', 'latin'), ('Anuphan', 'latin-ext'), ('Inter', 'latin'), ('Inter', 'latin-ext')}
BLOCK = re.compile(r"/\* ([\w-]+) \*/\s*@font-face\s*\{(.*?)\}", re.S)


def get(url):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def main():
    css = get(API).decode('utf-8')
    faces = {}
    for subset, body in BLOCK.findall(css):
        family = re.search(r"font-family:\s*'([^']+)'", body).group(1)
        if (family, subset) not in KEEP:
            continue
        weight = int(re.search(r'font-weight:\s*(\d+)', body).group(1))
        url = re.search(r'url\((https://[^)]+\.woff2)\)', body).group(1)
        rng = re.search(r'unicode-range:\s*([^;]+);', body).group(1).strip()
        faces.setdefault((family, subset, url), {'weights': set(), 'range': rng})['weights'].add(weight)

    FONTS.mkdir(parents=True, exist_ok=True)
    out = ['/* Inter + Anuphan · self-hosted (SIL Open Font License, assets/fonts/OFL.txt)',
           '   Generated by dev/tools/fetch-fonts.py · weights 400 to 700 */']
    per_subset = {}
    for (family, subset, url), info in sorted(faces.items()):
        per_subset.setdefault((family, subset), []).append((url, info))
    for (family, subset), items in sorted(per_subset.items()):
        variable = len(items) == 1
        for url, info in items:
            w = sorted(info['weights'])
            name = f'{family.lower()}-{subset}' + ('' if variable else f'-{w[0]}') + '.woff2'
            (FONTS / name).write_bytes(get(url))
            weight = f'{w[0]} {w[-1]}' if variable and len(w) > 1 else str(w[0])
            out.append('@font-face {\n'
                       f"\tfont-family: '{family}';\n\tfont-style: normal;\n\tfont-weight: {weight};\n\tfont-display: swap;\n"
                       f"\tsrc: url('../fonts/{name}') format('woff2');\n\tunicode-range: {info['range']};\n}}")
            print(name, (FONTS / name).stat().st_size, 'bytes', weight)
    CSS.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print('wrote', CSS.relative_to(THEME.parent))


if __name__ == '__main__':
    main()
