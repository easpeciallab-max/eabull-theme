/**
 * เอกสารยาว .doclay: สารบัญ (details.toc) + article.doc.paper
 * เนื้อหาเพจผ่าน the_content ตามปกติ (สารบัญจาก H2 · FAQ schema · ลิงก์ร่าง) แล้วแทรกเช็กลิสต์จาก Customizer
 * หลังหัวข้อ H2 ที่ {p}_check_after (0 = ก่อนหัวข้อแรก)
 */
function eab_guide_doc( $p, $band = 'band' ) {
	$GLOBALS['eab_guides_doc'] = true;
	$GLOBALS['eab_toc']        = array();
	$content                   = eab_guide_nocaps( (string) apply_filters( 'the_content', get_the_content() ) );
	$GLOBALS['eab_guides_doc'] = false;

	$toc = array();
	foreach ( (array) $GLOBALS['eab_toc'] as $item ) {
		if ( isset( $item['level'] ) && 2 === (int) $item['level'] ) {
			$toc[] = array(
				'id'   => $item['id'],
				'text' => $item['text'],
			);
		}
	}

	$check_title = trim( (string) eab_mod( $p . '_check_title' ) );
	$check_lines = eab_lines( eab_mod( $p . '_check' ) );
	if ( $check_lines ) {
		$id    = sanitize_key( $p . '-check' );
		$html  = '' !== $check_title ? '<h2 id="' . esc_attr( $id ) . '">' . eab_guide_inline( $check_title ) . '</h2>' : '';
		$html .= '<ul class="checks">';
		foreach ( $check_lines as $line ) {
			$html .= '<li>' . eab_icon( 'check' ) . '<span>' . eab_guide_inline( $line ) . '</span></li>';
		}
		$html .= '</ul>';

		$after  = max( 0, (int) eab_mod( $p . '_check_after' ) );
		$pieces = preg_split( '/(?=<h2[\s>])/i', $content );
		$after  = min( $after, count( $pieces ) - 1 );
		/* $pieces[0] = เนื้อหาก่อน H2 แรก · ชิ้นถัดไปขึ้นต้นด้วย H2 */
		array_splice( $pieces, $after + 1, 0, array( $html ) );
		$content = implode( '', $pieces );
		if ( '' !== $check_title ) {
			array_splice(
				$toc,
				min( $after, count( $toc ) ),
				0,
				array(
					array(
						'id'   => $id,
						'text' => eab_guide_plain( $check_title ),
					),
				)
			);
		}
	}

	if ( '' === trim( wp_strip_all_tags( $content ) ) ) {
		return;
	}
	$toc_title = trim( (string) eab_mod( 'guides_toc_title' ) );
	?>
	<section class="<?php echo esc_attr( $band ); ?>" aria-label="<?php echo esc_attr( eab_mod( 'guides_doc_label' ) ); ?>">
		<div class="wrap doclay">
			<?php if ( ! empty( $toc ) ) : ?>
				<details class="toc" open>
					<summary><?php echo esc_html( $toc_title ) . eab_icon( 'chevron-down' ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside ?></summary>
					<ol>
						<?php foreach ( $toc as $item ) : ?>
							<li><a href="#<?php echo esc_attr( $item['id'] ); ?>"><?php echo eab_guide_nocaps( esc_html( $item['text'] ) ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside ?></a></li>
						<?php endforeach; ?>
					</ol>
				</details>
			<?php endif; ?>
			<article class="doc paper">
				<?php echo $content; // phpcs:ignore WordPress.Security.EscapeOutput -- the_content ?>
			</article>
		</div>
	</section>
	<?php
}

/**
 * ตารางในเอกสารของหน้าคู่มือ: ใส่ data-label ให้ทุกช่อง td จากหัวตาราง + คลาส table-wrap--stack
 * จอแคบ (≤640px) ตารางเรียงเป็นการ์ดทีละแถว (style.css ส่วน 18) · ตารางที่มี data-label อยู่แล้วไม่ถูกแตะ
 * ช่องแรกของแถวเป็น <th scope="row"> ได้ (นับคอลัมน์ทั้ง th และ td)
 */
function eab_guide_stack_tables( $content ) {
	if ( empty( $GLOBALS['eab_guides_doc'] ) || false === stripos( (string) $content, '<table' ) ) {
		return $content;
	}
	$out = preg_replace_callback(
		'#<div class="table-wrap">(\s*<table\b.*?</table>\s*)</div>#is',
		function ( $m ) {
			$table = $m[1];
			if ( false !== stripos( $table, 'data-label=' ) || ! preg_match( '#<thead\b.*?</thead>#is', $table, $head ) ) {
				return $m[0];
			}
			preg_match_all( '#<th\b[^>]*>(.*?)</th>#is', $head[0], $ths );
			$labels = array_map(
				function ( $th ) {
					return trim( html_entity_decode( wp_strip_all_tags( $th ), ENT_QUOTES, 'UTF-8' ) );
				},
				$ths[1]
			);
			if ( count( $labels ) < 2 ) {
				return $m[0];
			}
			$body = preg_replace_callback(
				'#<tbody\b.*?</tbody>#is',
				function ( $tbody ) use ( $labels ) {
					return preg_replace_callback(
						'#<tr\b[^>]*>.*?</tr>#is',
						function ( $row ) use ( $labels ) {
							$col = 0;
							return preg_replace_callback(
								'#<(td|th)(?=[\s>])#i',
								function ( $cell ) use ( $labels, &$col ) {
									$label = isset( $labels[ $col ] ) ? $labels[ $col ] : '';
									$col++;
									return 'td' === strtolower( $cell[1] ) ? '<td data-label="' . esc_attr( $label ) . '"' : $cell[0];
								},
								$row[0]
							);
						},
						$tbody[0]
					);
				},
				$table
			);
			return '<div class="table-wrap table-wrap--stack">' . ( null === $body ? $table : $body ) . '</div>';
		},
		(string) $content
	);
	return null === $out ? $content : $out;
}
add_filter( 'the_content', 'eab_guide_stack_tables', 27 );

/**
 * คู่มือที่เกี่ยวข้อง .related > a.rel · แสดงเฉพาะการ์ดที่ไปยังเพจที่เผยแพร่แล้ว
 */
function eab_guide_related( $p, $band = 'band band--alt' ) {
	$cards = '';
	foreach ( eab_lines( eab_mod( $p . '_related' ) ) as $line ) {
		$parts = array_pad( eab_guide_split( $line, 4 ), 4, '' );
		if ( '' === $parts[0] || '' === $parts[1] ) {
			continue;
		}
		$slug = trim( $parts[0], '/' );
		if ( preg_match( '#^https?://#i', $parts[0] ) ) {
			$url = $parts[0];
		} elseif ( function_exists( 'eab_published_page_url' ) && '' !== $slug && false === strpos( $slug, '/' ) ) {
			$url = eab_published_page_url( $slug );
		} else {
			$url = eab_link_url( $parts[0] );
		}
		if ( '' === $url ) {
			continue;
		}
		$cards .= '<a class="rel" href="' . esc_url( $url ) . '"><span class="tile">' . eab_icon( '' !== $parts[3] ? $parts[3] : 'book' ) . '</span><span><b>' . eab_guide_inline( $parts[1] ) . '</b>'
			. ( '' !== $parts[2] ? '<small>' . eab_guide_inline( $parts[2] ) . '</small>' : '' ) . '</span>' . eab_icon( 'arrow-right' ) . '</a>';
	}
	if ( '' === $cards ) {
		return;
	}
	$title = trim( (string) eab_mod( 'guides_more_title' ) );
	?>
	<section class="<?php echo esc_attr( $band ); ?>"<?php echo '' !== $title ? ' aria-labelledby="rel-title"' : ''; ?>>
		<div class="wrap">
			<?php if ( '' !== $title ) : ?>
				<div class="shead"><div class="shead__text"><h2 id="rel-title"><?php echo eab_guide_bars() . esc_html( $title ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside ?></h2></div></div>
			<?php endif; ?>
			<div class="related"><?php echo $cards; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside ?></div>
		</div>
	</section>
	<?php
}

