/**
 * แปลงข้อมูลซ้อนเป็นคีย์ setting
 */
function eab_guide_flat_defaults() {
	$flat   = array();
	$images = eab_guide_images();
	foreach ( eab_guide_data() as $p => $g ) {
		foreach ( array( 'sub', 'intro', 'prep', 'prep_note' ) as $field ) {
			$flat[ eab_guide_k( $p, $field ) ] = $g[ $field ];
		}
		foreach ( array( 'crumb', 'meta', 'hero_btns', 'quick', 'intro_more', 'intro_btns', 'steps_title', 'check_title', 'check', 'check_after', 'related', 'cta_title', 'cta_text' ) as $field ) {
			$flat[ $p . '_' . $field ] = $g[ $field ];
		}
		for ( $i = 1; $i <= eab_guide_step_count(); $i++ ) {
			$s = isset( $g['steps'][ $i - 1 ] ) ? $g['steps'][ $i - 1 ] : array();
			$s = array_pad( $s, 7, '' );
			$k = $p . '_step' . $i;

			$flat[ $k . '_short' ]       = $s[0];
			$flat[ $k . '_title' ]       = $s[1];
			$flat[ $k . '_desc' ]        = $s[2];
			$flat[ $k . '_btns' ]        = $s[3];
			$img = isset( $images[ $p ][ $i ] ) ? array_pad( $images[ $p ][ $i ], 3, '' ) : array( '', '', '' );

			$flat[ $k . '_img' ]         = '' !== $img[0] ? 'assets/img/' . $img[0] : '';
			$flat[ $k . '_img_alt' ]     = $img[2];
			$flat[ $k . '_img_caption' ] = '' !== $img[1] ? $img[1] : $s[4];
			$flat[ $k . '_img_icon' ]    = '' !== $s[5] ? $s[5] : 'file';
			$flat[ $k . '_img_tall' ]    = ! empty( $s[6] );
		}
		if ( in_array( $p, eab_guide_app_prefixes(), true ) ) {
			for ( $n = 1; $n <= eab_guide_app_count(); $n++ ) {
				$a = isset( $g['apps'][ $n - 1 ] ) ? $g['apps'][ $n - 1 ] : array();
				$a = array_pad( $a, 6, '' );
				$k = $p . '_app' . $n;

				$flat[ $k . '_icon' ]  = '' !== $a[0] ? $a[0] : 'download';
				$flat[ $k . '_name' ]  = $a[1];
				$flat[ $k . '_store' ] = $a[2];
				$flat[ $k . '_text' ]  = $a[3];
				$flat[ $k . '_url' ]   = $a[4];
				$flat[ $k . '_btn' ]   = $a[5];
			}
		}
	}

	$flat += eab_guide_tools_defaults();

	foreach ( array_keys( eab_guide_facts() ) as $fact ) {
		$flat[ 'guide_fact_' . $fact ] = '';
	}

	/* ตั้งค่าร่วมทุกหน้าคู่มือ */
	$flat['guides_sum_title']   = 'สรุปแบบสั้น';
	$flat['guides_intro_title'] = 'ก่อนเริ่ม';
	$flat['guides_prep_title']  = 'ต้องมีก่อนเริ่ม';
	$flat['guides_rail_title']  = 'ขั้นตอน';
	$flat['guides_rail_label']  = 'ขั้นตอนในหน้านี้';
	$flat['guides_img_label']   = 'ภาพ';
	$flat['guides_shot_wait']   = 'ภาพหน้าจอ รอจากเจ้าของ';
	$flat['guides_toc_title']   = 'ในหน้านี้';
	$flat['guides_doc_label']   = 'รายละเอียดเพิ่มเติม';
	$flat['guides_more_title']  = 'คู่มือที่เกี่ยวข้อง';
	$flat['guides_portal_url']  = ''; // ลิงก์เข้า Portal ของโบรกเกอร์ (ที่ได้มาเป็นลิงก์สมัคร) · รอเจ้าของยืนยัน
	$flat['guides_portal_wait'] = 'ลิงก์เข้า Portal รอยืนยันจากเจ้าของ';

	return $flat;
}

