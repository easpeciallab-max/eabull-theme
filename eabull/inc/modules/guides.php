/**
 * แทนตัวแทน {brand} {broker} {server} ด้วยค่าจริง (ทำก่อน escape)
 */
function eab_guide_tokens( $text ) {
	$text = (string) $text;
	if ( false === strpos( $text, '{' ) ) {
		return $text;
	}
	$brand = trim( (string) eab_mod( 'hero_title' ) );
	return strtr(
		$text,
		array(
			'{brand}'  => '' !== $brand ? $brand : 'EA BULL',
			'{broker}' => (string) eab_mod( 'broker_name' ),
			'{server}' => (string) eab_mod( 'broker_server' ),
			'{ea}'         => eab_ea_name(),
			'{ea_file}'    => eab_ea_name() . '.ex5',
			'{ea_version}' => eab_ea_version(),
			'{bt_range}'   => eab_ea_bt_range(),
		)
	);
}

/**
 * กระเบื้องไอคอน Glass Sky (.tile จาก style.css ส่วน 43) · $tone = sky | gold | blue | navy
 */
function eab_guide_tile( $icon, $tone = 'gold', $class = '' ) {
	return '<span class="' . esc_attr( trim( 'tile tile--' . $tone . ' ' . $class ) ) . '" aria-hidden="true">' . eab_icon( $icon ) . '</span>';
}

/**
 * รายการแบบมีเครื่องหมายถูก · บรรทัด "หัวข้อ | รายละเอียด" = หัวข้อตัวหนา
 */
function eab_guide_marks( $text ) {
	$lines = eab_lines( eab_guide_tokens( $text ) );
	if ( empty( $lines ) ) {
		return '';
	}
	$html = '<ul class="gd-marks">';
	foreach ( $lines as $line ) {
		$parts = explode( ' | ', $line, 2 );
		$html .= '<li><span class="gd-mark" aria-hidden="true">' . eab_icon( 'check', 'icon' ) . '</span><span class="gd-mark-text">';
		if ( 2 === count( $parts ) ) {
			$html .= '<strong>' . eab_text( trim( $parts[0] ) ) . '</strong> ' . eab_rich_inline( trim( $parts[1] ) );
		} else {
			$html .= eab_rich_inline( $line );
		}
		$html .= '</span></li>';
	}
	return $html . '</ul>';
}

/**
 * ลำดับขั้นแบบย่อ (ข้อความคั่นด้วย →) · ลูกศรในวงเล็บไม่ถูกตัด
 */
function eab_guide_flow( $text ) {
	$blocks = preg_split( '/\n\s*\n/', trim( eab_guide_tokens( $text ) ), 2 );
	$first  = isset( $blocks[0] ) ? trim( $blocks[0] ) : '';
	$rest   = isset( $blocks[1] ) ? trim( $blocks[1] ) : '';
	$items  = array_values( array_filter( array_map( 'trim', (array) preg_split( '/\s*→\s*(?![^()]*\))/u', $first ) ), 'strlen' ) );
	$html   = '';
	if ( count( $items ) > 1 ) {
		$html .= '<ol class="gd-flow">';
		foreach ( $items as $item ) {
			$html .= '<li>' . eab_rich_inline( $item ) . '</li>';
		}
		$html .= '</ol>';
	} elseif ( '' !== $first ) {
		$html .= eab_rich_text( $first );
	}
	if ( '' !== $rest ) {
		$html .= '<div class="gd-flow-note">' . eab_rich_text( $rest ) . '</div>';
	}
	return $html;
}

