	$list  = array( 'how-to-install' => 'install' ) + eab_guide_map();
	$items = array();
	foreach ( $list as $slug => $p ) {
		if ( $slug === $current ) {
			continue;
		}
		$url = function_exists( 'eab_published_page_url' ) ? eab_published_page_url( $slug ) : '';
		if ( '' === $url ) {
			continue;
		}
