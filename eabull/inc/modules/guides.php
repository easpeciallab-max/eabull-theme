		$url   = trim( (string) eab_mod( $p . '_dl' . $i . '_url' ) );
		if ( '' === $label || '' === $url || '#' === $url ) {
			continue;
		}
		$icon    = strtolower( trim( (string) eab_mod( $p . '_dl' . $i . '_icon' ) ) );
