/**
 * แถบเส้นทาง: หน้าแรก / คู่มือการใช้งาน / หน้านี้ (ชุดเดียวกับ BreadcrumbList ใน inc/seo.php)
 */
function eab_guide_crumbs( $label ) {
	$crumbs = function_exists( 'eab_breadcrumbs' ) ? eab_breadcrumbs( $label ) : array(
		array(
			'name' => 'หน้าแรก',
			'url'  => home_url( '/' ),
		),
		array(
			'name' => $label,
			'url'  => '',
		),
	);
	/* หน้า How to Install เป็นหน้าแรกของกลุ่มคู่มือ · แสดงชื่อกลุ่มเป็นข้อความ (ไม่มีลิงก์) แบบต้นแบบ */
	if ( 2 === count( $crumbs ) && is_page( 'how-to-install' ) ) {
		$group = trim( (string) eab_mod( 'nav_guide_label' ) );
		array_splice(
			$crumbs,
			1,
			0,
			array(
				array(
					'name' => '' !== $group ? $group : 'คู่มือการใช้งาน',
					'url'  => '',
				),
			)
		);
	}
	$last = count( $crumbs ) - 1;
	echo '<nav aria-label="เส้นทางนำทาง"><ol class="crumbs">';
	foreach ( $crumbs as $i => $crumb ) {
		if ( $i < $last && ! empty( $crumb['url'] ) ) {
			echo '<li><a href="' . esc_url( $crumb['url'] ) . '">' . eab_guide_nocaps( esc_html( $crumb['name'] ) ) . '</a></li>'; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside
		} else {
			echo '<li' . ( $i === $last ? ' aria-current="page"' : '' ) . '>' . eab_guide_nocaps( esc_html( $crumb['name'] ) ) . '</li>'; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside
		}
	}
	echo '</ol></nav>';
}

/**
 * กล่องสรุปแบบสั้น: ข้อความคั่นด้วย → = ลำดับในบรรทัดเดียว (.flow) · หลายบรรทัด = รายการเลขลำดับ
 */
function eab_guide_quick( $text, $ctx = array() ) {
	$text = trim( (string) $text );
	if ( '' === $text ) {
		return '';
	}
	if ( false !== strpos( $text, '→' ) ) {
		$items = array_values( array_filter( array_map( 'trim', explode( '→', $text ) ), 'strlen' ) );
		$sep   = ' ' . eab_icon( 'chevron-right' ) . ' ';
		return '<p class="flow">' . implode( $sep, array_map( 'eab_guide_inline', $items, array_fill( 0, count( $items ), $ctx ) ) ) . '</p>';
	}
	$html = '';
	foreach ( eab_lines( $text ) as $n => $line ) {
		$html .= '<li><b>' . ( $n + 1 ) . '</b><span>' . eab_guide_inline( $line, $ctx ) . '</span></li>';
	}
	return '<ol>' . $html . '</ol>';
}

