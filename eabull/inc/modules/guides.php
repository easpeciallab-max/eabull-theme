/**
 * ห่อคำอังกฤษที่ต้องคงตัวพิมพ์ด้วย .nocaps (ทั้งเว็บแสดงภาษาอังกฤษเป็นพิมพ์ใหญ่) · แตะเฉพาะข้อความ ไม่แตะแท็ก
 */
function eab_guide_nocaps( $html ) {
	$words = (array) apply_filters( 'eab_guide_nocaps_words', array( 'iPhone', 'iPad', 'iOS', 'mstsc', 'ms', '.zip', '.ex5', 'portal.zaurix.com', 'metatrader5.com' ) );
	$words = array_map(
		function ( $w ) {
			return preg_quote( (string) $w, '/' );
		},
		$words
	);
	$re    = '/(?<![A-Za-z0-9_.\/-])(' . implode( '|', $words ) . ')(?![A-Za-z0-9_-])/';
	$parts = preg_split( '/(<[^>]*>)/', (string) $html, -1, PREG_SPLIT_DELIM_CAPTURE );
	if ( false === $parts ) {
		return $html;
	}
	$skip = 0;
	$raw  = false;
	foreach ( $parts as $idx => $part ) {
		if ( '' === $part ) {
			continue;
		}
		if ( '<' === $part[0] ) {
			/* ไม่แตะ <script> <style> <textarea> · ข้อความใน <span class="nocaps"> ที่มีอยู่แล้วไม่ต้องห่อซ้ำ */
			if ( preg_match( '#^<(script|style|textarea)\b#i', $part ) ) {
				$raw = true;
			} elseif ( preg_match( '#^</(script|style|textarea)\b#i', $part ) ) {
				$raw = false;
			} elseif ( $skip && preg_match( '#^</span#i', $part ) ) {
				$skip--;
			} elseif ( $skip && preg_match( '#^<span\b#i', $part ) ) {
				$skip++;
			} elseif ( preg_match( '#^<span class="nocaps"#i', $part ) ) {
				$skip = 1;
			}
			continue;
		}
		if ( ! $skip && ! $raw ) {
			$parts[ $idx ] = (string) preg_replace( $re, '<span class="nocaps">$1</span>', $part );
		}
	}
	return implode( '', $parts );
}

/**
 * แทนตัวแทนใน HTML ที่ escape แล้ว: {brand} {broker} {server} {steps} {wait} {fact:ชื่อ}
 */
function eab_guide_fill( $html, $ctx = array() ) {
	if ( false === strpos( (string) $html, '{' ) ) {
		return (string) $html;
	}
	$facts = eab_guide_facts();
	return (string) preg_replace_callback(
		'/\{(brand|broker|server|steps|wait|fact:[a-z0-9_]+)\}/',
		function ( $m ) use ( $ctx, $facts ) {
			switch ( $m[1] ) {
				case 'brand':
					return esc_html( eab_guide_brand() );
				case 'broker':
					return eab_wait( eab_mod( 'broker_name' ) );
				case 'server':
					$server = trim( (string) eab_mod( 'broker_server' ) );
					return '' === $server ? eab_wait( '' ) : '<span class="nocaps">' . esc_html( $server ) . '</span>';
				case 'steps':
					return isset( $ctx['steps'] ) ? (string) (int) $ctx['steps'] : '';
				case 'wait':
					return eab_wait( '' );
			}
			$fact  = substr( $m[1], 5 );
			$value = trim( (string) eab_mod( 'guide_fact_' . $fact ) );
			if ( '' !== $value && ! empty( $facts[ $fact ][1] ) ) {
				return '<span class="nocaps">' . esc_html( $value ) . '</span>';
			}
			return eab_wait( $value );
		},
		(string) $html
	);
}

/**
 * ข้อความล้วน (สำหรับ alt / aria-label / data-*) · ตัวแทนที่ยังไม่มีค่าเป็นค่าว่าง
 */
function eab_guide_plain( $text ) {
	$text = (string) $text;
	if ( false === strpos( $text, '{' ) ) {
		return trim( preg_replace( '/\*\*(.+?)\*\*/u', '$1', $text ) );
	}
	$text = (string) preg_replace_callback(
		'/\{(brand|broker|server|fact:[a-z0-9_]+)\}/',
		function ( $m ) {
			if ( 'brand' === $m[1] ) {
				return eab_guide_brand();
			}
			if ( 'broker' === $m[1] ) {
				return (string) eab_mod( 'broker_name' );
			}
			if ( 'server' === $m[1] ) {
				return (string) eab_mod( 'broker_server' );
			}
			return (string) eab_mod( 'guide_fact_' . substr( $m[1], 5 ) );
		},
		$text
	);
	return trim( preg_replace( '/\*\*(.+?)\*\*/u', '$1', $text ) );
}

/**
 * ข้อความในบรรทัด: escape ทั้งหมด แล้วแปลง **ตัวหนา** [ข้อความ](/slug/) และตัวแทน
 * ลิงก์ไปเพจที่ยังเป็นฉบับร่างกลายเป็นข้อความธรรมดา (eab_unreachable_slugs ใน inc/setup.php)
 */
function eab_guide_inline( $text, $ctx = array() ) {
	$html = esc_html( trim( (string) $text ) );
	$html = (string) preg_replace_callback(
		'#\[([^\[\]\n]+)\]\(((?:/(?!/)|\#)[^\s()<>]*)\)#u',
		function ( $m ) {
			$path = html_entity_decode( $m[2], ENT_QUOTES, 'UTF-8' );
			if ( '#' === $path[0] ) {
				return '<a href="' . esc_attr( $path ) . '">' . $m[1] . '</a>';
			}
			$slug = (string) strtok( trim( $path, '/' ), '/?#' );
			if ( '' !== $slug && function_exists( 'eab_unreachable_slugs' ) && in_array( $slug, eab_unreachable_slugs(), true ) ) {
				return $m[1];
			}
			return '<a href="' . esc_url( home_url( $path ) ) . '">' . $m[1] . '</a>';
		},
		$html
	);
	$html = (string) preg_replace( '/\*\*(.+?)\*\*/u', '<b>$1</b>', $html );
	return eab_guide_fill( eab_guide_nocaps( $html ), $ctx );
}

/**
 * แยกบรรทัด "ส่วนที่ 1 | ส่วนที่ 2 | ..." (ไม่สนช่องว่างรอบ |)
 */
function eab_guide_split( $line, $limit = -1 ) {
	return array_map( 'trim', explode( '|', (string) $line, $limit ) );
}

/**
 * กล่องหมายเหตุ .note · ข้อความขึ้นต้น !info !warn !tip !bad !ok เลือกสี (ไม่ใส่ = info)
 */
function eab_guide_note( $text, $ctx = array(), $class = '' ) {
	$text = trim( (string) $text );
	if ( '' === $text ) {
		return '';
	}
	$type = 'info';
	if ( preg_match( '/^!(info|warn|tip|bad|ok)\s*/', $text, $m ) ) {
		$type = $m[1];
		$text = substr( $text, strlen( $m[0] ) );
	} elseif ( '!' === $text[0] ) {
		$text = ltrim( substr( $text, 1 ) );
	}
	$icons = array(
		'info' => 'info',
		'warn' => 'alert',
		'tip'  => 'bulb',
		'bad'  => 'x',
		'ok'   => 'check',
	);
	return '<p class="' . esc_attr( trim( 'note note--' . $type . ' ' . $class ) ) . '">' . eab_icon( $icons[ $type ] ) . '<span>' . eab_guide_inline( $text, $ctx ) . '</span></p>';
}

/**
 * แถวข้อมูล <dl> แบบกล่อง .prep จากบรรทัด "หัวข้อ | รายละเอียด"
 */
function eab_guide_dl( $lines, $ctx = array() ) {
	$rows = '';
	foreach ( (array) $lines as $line ) {
		$parts = eab_guide_split( $line, 2 );
		if ( count( $parts ) < 2 ) {
			continue;
		}
		$rows .= '<div><dt>' . eab_guide_inline( $parts[0], $ctx ) . '</dt><dd>' . eab_guide_inline( $parts[1], $ctx ) . '</dd></div>';
	}
	return '' !== $rows ? '<dl>' . $rows . '</dl>' : '';
}

/**
 * ข้อความหลายบล็อกของขั้นตอน · คืน array( body, dl, notes ) ให้ผู้เรียกจัดลำดับตามต้นแบบ
 * (ย่อหน้าและรายการ → กล่องข้อมูล → ปุ่ม → การ์ดแอป → หมายเหตุ → ภาพ)
 */
function eab_guide_blocks( $text, $ctx = array() ) {
	$out  = array(
		'body'  => '',
		'dl'    => '',
		'notes' => '',
	);
	$text = trim( str_replace( array( "\r\n", "\r" ), "\n", (string) $text ) );
	if ( '' === $text ) {
		return $out;
	}
	$dl = array();
	foreach ( preg_split( '/\n\s*\n/', $text ) as $block ) {
		$lines = array_values( array_filter( array_map( 'trim', explode( "\n", $block ) ), 'strlen' ) );
		if ( empty( $lines ) ) {
			continue;
		}
		if ( '!' === $lines[0][0] ) {
			$note = '';
			foreach ( $lines as $line ) {
				if ( '!' === $line[0] && '' !== $note ) {
					$out['notes'] .= eab_guide_note( $note, $ctx );
					$note          = '';
				}
				$note .= ( '' !== $note ? ' ' : '' ) . $line;
			}
			$out['notes'] .= eab_guide_note( $note, $ctx );
			continue;
		}
		$all = function ( $re ) use ( $lines ) {
			foreach ( $lines as $line ) {
				if ( ! preg_match( $re, $line ) ) {
					return false;
				}
			}
			return true;
		};
		if ( $all( '/^-\s+/' ) ) {
			$out['body'] .= '<ul>';
			foreach ( $lines as $line ) {
				$out['body'] .= '<li>' . eab_guide_inline( preg_replace( '/^-\s+/', '', $line ), $ctx ) . '</li>';
			}
			$out['body'] .= '</ul>';
			continue;
		}
		if ( $all( '/^\d+\.\s+/' ) ) {
			$out['body'] .= '<ol>';
			foreach ( $lines as $line ) {
				$out['body'] .= '<li>' . eab_guide_inline( preg_replace( '/^\d+\.\s+/', '', $line ), $ctx ) . '</li>';
			}
			$out['body'] .= '</ol>';
			continue;
		}
		if ( $all( '/\S\s*\|\s*\S/' ) ) {
			$dl = array_merge( $dl, $lines );
			continue;
		}
		$out['body'] .= '<p>' . implode( '<br>', array_map( 'eab_guide_inline', $lines, array_fill( 0, count( $lines ), $ctx ) ) ) . '</p>';
	}
	$out['dl'] = eab_guide_dl( $dl, $ctx );
	return $out;
}

/**
 * ปุ่มจากบรรทัด "ข้อความ | ปลายทาง | ไอคอน"
 *
 * @param string $text  ค่าใน setting
 * @param array  $args  { first: primary|light|outline (แบบของปุ่มแรกที่ลิงก์ในเว็บ), size: '' | btn--sm, pos: data-line-pos }
 */
function eab_guide_buttons( $text, $args = array() ) {
	$args = wp_parse_args(
		$args,
		array(
			'first' => 'primary',
			'size'  => '',
			'pos'   => 'guide',
		)
	);
	$html = '';
	$i    = 0;
	foreach ( eab_lines( $text ) as $line ) {
		$parts = eab_guide_split( $line, 3 );
		$label = $parts[0];
		$dest  = isset( $parts[1] ) ? $parts[1] : '';
		$icon  = isset( $parts[2] ) ? $parts[2] : '';
		if ( '' === $label || '' === $dest ) {
			continue;
		}
		$size = '' !== $args['size'] ? ' ' . $args['size'] : '';

		if ( 'line' === $dest ) {
			ob_start();
			eab_contact_button(
				array(
					'text'  => eab_guide_plain( $label ),
					'class' => 'btn btn--line' . $size,
					'pos'   => $args['pos'],
					'arrow' => false,
				)
			);
			$html .= (string) ob_get_clean();
			$i++;
			continue;
		}

		$attrs    = '';
		$external = false;
		if ( 'signup' === $dest ) {
			$url      = trim( (string) eab_mod( 'broker_signup_url' ) );
			$attrs    = ' target="_blank" rel="sponsored noopener"';
			$external = true;
			$class    = 'btn btn--primary';
		} elseif ( 'portal' === $dest ) {
			$url      = trim( (string) eab_mod( 'guides_portal_url' ) );
			$attrs    = '' !== $url ? ' target="_blank" rel="noopener"' : ' data-wait="' . esc_attr( eab_mod( 'guides_portal_wait' ) ) . '"';
			$external = true;
			$class    = 'btn btn--primary';
		} elseif ( preg_match( '#^https?://#i', $dest ) ) {
			$url      = $dest;
			$attrs    = ' target="_blank" rel="noopener"';
			$external = true;
			$class    = 'btn btn--primary';
		} else {
			$url   = eab_link_url( $dest );
			$class = 'btn btn--' . ( 0 === $i ? $args['first'] : 'outline' );
		}
		if ( '' === $url ) {
			$url = '#';
		}
		if ( '' === $icon && $external ) {
			$icon = 'external';
		}
		$svg   = '' !== $icon ? eab_icon( $icon ) : '';
		$after = in_array( $icon, array( 'arrow-right', 'external', 'chevron-right', 'arrow-up-right' ), true );
		$html .= '<a class="' . esc_attr( $class . $size ) . '" href="' . esc_url( $url ) . '"' . $attrs . '>'
			. ( $after ? '' : $svg ) . eab_guide_inline( $label ) . ( $after ? ' ' . $svg : '' ) . '</a>';
		$i++;
	}
	return $html;
}

