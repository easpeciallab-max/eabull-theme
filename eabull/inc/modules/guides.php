/**
 * การ์ดแอปในขั้นที่ 1 (ลิงก์ร้านแอปทางการ) · 2 ใบขึ้นไป = .apps · ใบเดียว = ครึ่งความกว้าง (.grid.g2) แบบต้นแบบ
 */
function eab_guide_apps( $p ) {
	if ( ! in_array( $p, eab_guide_app_prefixes(), true ) ) {
		return '';
	}
	$cards = array();
	for ( $n = 1; $n <= eab_guide_app_count(); $n++ ) {
		$k    = $p . '_app' . $n;
		$name = trim( (string) eab_mod( $k . '_name' ) );
		$url  = trim( (string) eab_mod( $k . '_url' ) );
		if ( '' === $name || '' === $url ) {
			continue;
		}
		$store   = trim( (string) eab_mod( $k . '_store' ) );
		$text    = trim( (string) eab_mod( $k . '_text' ) );
		$btn     = trim( (string) eab_mod( $k . '_btn' ) );
		$cards[] = '<div class="app"><div class="app__head"><span class="tile">' . eab_icon( trim( (string) eab_mod( $k . '_icon' ) ) ) . '</span><span><b>' . eab_guide_inline( $name ) . '</b>'
			. ( '' !== $store ? '<small>' . eab_guide_inline( $store ) . '</small>' : '' ) . '</span></div>'
			. ( '' !== $text ? '<p>' . eab_guide_inline( $text ) . '</p>' : '' )
			. '<a class="btn btn--light btn--sm" href="' . esc_url( $url ) . '" target="_blank" rel="noopener">' . eab_guide_inline( '' !== $btn ? $btn : $name ) . ' ' . eab_icon( 'external' ) . '</a></div>';
	}
	if ( empty( $cards ) ) {
		return '';
	}
	return 1 === count( $cards ) ? '<div class="grid g2 mt-16">' . $cards[0] . '</div>' : '<div class="apps">' . implode( '', $cards ) . '</div>';
}

/**
 * ช่องภาพของขั้น: มีภาพ (ไฟล์ในธีมที่มีอยู่จริง หรือภาพที่อัปโหลด) = รูปจริงขนาดตามไฟล์ เปิดดูขนาดเต็มได้
 * ไม่มีภาพแต่มีชื่อภาพ = กรอบ .shot "ภาพหน้าจอ รอจากเจ้าของ" แบบต้นแบบ · ภาพแนวตั้งดูจากขนาดไฟล์ (กรอบที่รอภาพดูจาก _img_tall)
 */
function eab_guide_shot( $k, $n, $eager = false ) {
	$value   = trim( (string) eab_mod( $k . '_img' ) );
	$caption = eab_guide_plain( eab_mod( $k . '_img_caption' ) );
	$tall    = (bool) eab_mod( $k . '_img_tall' );
	$label   = trim( trim( (string) eab_mod( 'guides_img_label' ) ) . ' ' . sprintf( '%02d', $n ) );
	$full    = '' !== $caption ? $label . ' · ' . $caption : $label;
	$size    = array(
		'width'  => $tall ? 720 : 1280,
		'height' => $tall ? 1280 : 720,
	);
	$src     = '';
	if ( 0 === strpos( $value, 'assets/' ) ) {
		/* ภาพที่มากับธีม: ใช้เมื่อไฟล์มีอยู่จริง · ขนาดจากไฟล์ */
		$file = get_template_directory() . '/' . $value;
		$dim  = is_readable( $file ) ? @getimagesize( $file ) : false; // phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged
		if ( $dim ) {
			$src  = get_template_directory_uri() . '/' . $value;
			$size = array(
				'width'  => (int) $dim[0],
				'height' => (int) $dim[1],
			);
		}
	} elseif ( '' !== $value ) {
		/* ภาพที่อัปโหลดใน Customizer */
		$src = $value;
		if ( function_exists( 'eab_media_info' ) ) {
			$size = eab_media_info( $src, $size['width'], $size['height'] );
		}
	}

	if ( '' !== $src ) {
		$alt  = eab_guide_plain( eab_mod( $k . '_img_alt' ) );
		$tall = (int) $size['height'] > (int) $size['width'];
		return '<figure class="gshot' . ( $tall ? ' gshot--tall' : '' ) . '"><a class="lightbox" href="' . esc_url( $src ) . '" target="_blank" rel="noopener" data-group="steps" data-caption="' . esc_attr( $full ) . '">'
			. '<img src="' . esc_url( $src ) . '" alt="' . esc_attr( '' !== $alt ? $alt : $caption ) . '" width="' . (int) $size['width'] . '" height="' . (int) $size['height'] . '" loading="' . ( $eager ? 'eager' : 'lazy' ) . '" decoding="async"></a>'
			. '<figcaption class="cap">' . eab_guide_nocaps( esc_html( $full ) ) . '</figcaption></figure>';
	}
	if ( '' === $caption ) {
		return '';
	}
	$icon = trim( (string) eab_mod( $k . '_img_icon' ) );
	return '<div class="shot' . ( $tall ? ' shot--tall' : '' ) . '">' . eab_icon( '' !== $icon ? $icon : 'file' ) . '<span><b>' . eab_guide_nocaps( esc_html( $full ) ) . '</b>' . esc_html( eab_mod( 'guides_shot_wait' ) ) . '</span></div>';
}

