	}
	$title  = trim( (string) eab_mod( $p . '_dl_title' ) );
	$btn    = trim( (string) eab_mod( 'guides_dl_btn' ) );
	$newtab = trim( (string) eab_mod( 'guides_newtab' ) );
	/* โทนกระเบื้องตามแพลตฟอร์ม */
	$tones = array(
		'windows'  => 'blue',
		'android'  => 'sky',
		'apple'    => 'navy',
		'download' => 'gold',
	);
	?>
	<div class="gd-dl reveal">
		<?php if ( '' !== $title ) : ?>
