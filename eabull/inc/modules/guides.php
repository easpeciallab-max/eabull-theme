/**
 * slug ของเพจ → prefix ของ setting (ลำดับ = ลำดับการใช้งานจริง)
 * หน้า How to Install ใช้ prefix 'inst' (template-install.php) · หน้า /tools/ ใช้ 'gtools'
 *
 * @return array<string,string>
 */
function eab_guide_map() {
	return apply_filters(
		'eab_guide_map',
		array(
			'open-mt5-account' => 'gacct',
			'deposit'          => 'gdep',
			'mt5-login'        => 'gmt5',
			'vps-windows'      => 'gvpsw',
			'vps-android'      => 'gvpsa',
			'vps-ios'          => 'gvpsi',
		)
	);
}

/**
 * prefix ของหน้าคู่มือที่กำลังแสดง ('' = ไม่ใช่หน้าคู่มือแบบขั้นตอน)
 */
function eab_guide_prefix( $post_id = 0 ) {
	$post_id = $post_id ? (int) $post_id : (int) get_queried_object_id();
	if ( ! $post_id ) {
		return '';
	}
	$slug = (string) get_post_field( 'post_name', $post_id );
	$map  = eab_guide_map();
	return isset( $map[ $slug ] ) ? $map[ $slug ] : '';
}

function eab_guide_step_count() {
	return 6;
}

function eab_guide_app_count() {
	return 3;
}

/**
 * หน้าที่มีการ์ดแอปในขั้นที่ 1 (ลิงก์ร้านแอปทางการ)
 */
function eab_guide_app_prefixes() {
	return array( 'gmt5', 'gvpsa', 'gvpsi' );
}

/**
 * ชื่อ setting ของแต่ละช่อง · หน้า How to Install ใช้คีย์ install_* เดิมของธีมบางช่อง
 */
function eab_guide_k( $p, $field ) {
	if ( 'inst' === $p ) {
		$map = array(
			'sub'       => 'install_sub',
			'intro'     => 'install_intro',
			'prep'      => 'install_req',
			'prep_note' => 'inst_req_note',
		);
		if ( isset( $map[ $field ] ) ) {
			return $map[ $field ];
		}
	}
	return $p . '_' . $field;
}

function eab_guide_get( $p, $field ) {
	return trim( (string) eab_mod( eab_guide_k( $p, $field ) ) );
}

