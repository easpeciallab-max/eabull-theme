/**
 * ตารางในเนื้อหา: ใส่ data-label ให้ทุก <td> ของ table.data-table จากหัวตาราง (มือถือแสดงเป็นการ์ด)
 */
function eab_pages_stack_tables( $html ) {
	if ( false === stripos( (string) $html, '<table' ) ) {
		return $html;
	}
	$html = preg_replace_callback( '#<table\b[^>]*\bdata-table\b[^>]*>.*?</table>#is', 'eab_pages_stack_table_cb', (string) $html );
	return preg_replace( '#<div class="table-wrap">#', '<div class="table-wrap table-wrap--stack">', $html );
}

function eab_pages_stack_table_cb( $match ) {
	$table = $match[0];
	if ( ! preg_match( '#<thead\b[^>]*>(.*?)</thead>#is', $table, $head ) ) {
		return $table;
	}
	preg_match_all( '#<th\b[^>]*>(.*?)</th>#is', $head[1], $cells );
	$labels = array();
	foreach ( $cells[1] as $cell ) {
		$labels[] = trim( wp_strip_all_tags( $cell ) );
	}
	if ( ! $labels ) {
		return $table;
	}
	return preg_replace_callback(
		'#<tr\b([^>]*)>(.*?)</tr>#is',
		function ( $row ) use ( $labels ) {
			$col   = 0;
			$inner = preg_replace_callback(
				'#<t([dh])\b([^>]*)>#i',
				function ( $td ) use ( &$col, $labels ) {
					$label = isset( $labels[ $col ] ) ? $labels[ $col ] : '';
					$col++;
					if ( 'h' === strtolower( $td[1] ) || '' === $label || false !== stripos( $td[2], 'data-label' ) ) {
						return $td[0];
					}
					return '<td' . $td[2] . ' data-label="' . esc_attr( $label ) . '">';
				},
				$row[2]
			);
			return '<tr' . $row[1] . '>' . $inner . '</tr>';
		},
		$table
	);
}

function eab_pages_enable_table_cards() {
	static $done = false;
	if ( ! $done ) {
		add_filter( 'the_content', 'eab_pages_stack_tables', 30 );
		$done = true;
	}
}

