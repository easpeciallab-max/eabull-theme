		$html .= '<article class="prow"><div class="prow__ver">' . ( '' !== $ver ? '<small>' . esc_html( $ver ) . '</small>' : '' ) . '<b>' . eab_wait( isset( $item['version'] ) ? $item['version'] : '' ) . '</b></div><div class="prow__body"><div>';
