}

/**
 * รายการเลขใหญ่ (.feat) จาก setting "หัวข้อ | ข้อความ | ข้อความลิงก์ | /slug/"
 */
function eab_pages_feat( $text ) {
	$html = '';
	$n    = 0;
	foreach ( eab_pages_rows( $text ) as $row ) {
		if ( '' === $row[0] ) {
			continue;
		}
		$n++;
		$html .= '<div class="feat__item"><span class="feat__n">' . sprintf( '%02d', $n ) . '</span><div><h3>' . eab_pages_fmt( $row[0] ) . '</h3>';
		if ( isset( $row[1] ) && '' !== $row[1] ) {
			$html .= '<p>' . eab_pages_fmt( $row[1] ) . '</p>';
		}
		if ( isset( $row[2], $row[3] ) ) {
			$html .= eab_pages_tlink( $row[2], $row[3] );
		}
		$html .= '</div></div>';
	}
	return '' === $html ? '' : '<div class="feat">' . $html . '</div>';
}

/**
 * กล่องข้อมูลแบบหัวข้อ/ค่า (.prep > dl) จาก setting "หัวข้อ | ข้อมูล"
 * ข้อมูลที่เป็นลิงก์ [ข้อความ](ลิงก์) ทั้งช่อง = ลิงก์ลูกศร .tlink · ข้อมูลว่าง = ป้ายรอข้อมูล
 */
function eab_pages_dl( $title, $rows, $icon = 'info', $pos = 'content' ) {
	$html = '';
	foreach ( eab_pages_pairs( $rows ) as $pair ) {
		$value = trim( $pair[1] );
		if ( preg_match( '#^\[([^\[\]\n]+)\]\(([^()\s]+)\)$#u', $value, $m ) ) {
			$dd = eab_pages_tlink( $m[1], $m[2], '', $pos );
			$dd = '' !== $dd ? $dd : eab_pages_fmt( $m[1] );
		} else {
			$dd = '' !== $value ? eab_pages_fmt( $value ) : eab_wait( '' );
		}
		$html .= '<div><dt>' . eab_pages_fmt( $pair[0] ) . '</dt><dd>' . $dd . '</dd></div>';
	}
	if ( '' === $html ) {
		return '';
	}
	return '<div class="prep">' . ( '' !== trim( (string) $title ) ? '<h3>' . eab_icon( $icon ) . eab_text( $title ) . '</h3>' : '' ) . '<dl>' . $html . '</dl></div>';
}

/**
