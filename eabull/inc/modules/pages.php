/* ==============================================================
 * Breadcrumb ของหน้าในชุดนี้ (ชื่อสั้นจาก setting · ใช้ทั้งที่เห็นบนหน้าและ BreadcrumbList)
 * ============================================================== */

add_filter( 'eab_breadcrumb_current', 'eab_pages_breadcrumb_current', 10, 2 );

function eab_pages_breadcrumb_current( $name, $slug ) {
	$keys = eab_pages_keys();
	if ( isset( $keys[ $slug ] ) ) {
		$crumb = trim( (string) eab_mod( $keys[ $slug ] . '_crumb' ) );
		if ( '' !== $crumb ) {
			return $crumb;
		}
	}
	return $name;
}

