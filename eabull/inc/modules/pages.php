/**
 * breadcrumb (ol.crumbs) จาก eab_breadcrumbs() · ชุดเดียวกับ BreadcrumbList ใน inc/seo.php
 *
 * @param string $title     ชื่อหน้าปัจจุบัน
 * @param bool   $hide_last ไม่แสดงรายการสุดท้าย (หน้าบทความ: จบที่หมวดตามต้นแบบ)
 */
function eab_pages_crumbs_html( $title = '', $hide_last = false ) {
	$crumbs = eab_breadcrumbs( $title );
	if ( $hide_last && count( $crumbs ) > 2 ) {
		array_pop( $crumbs );
		$hide_last = 'done';
	}
	if ( count( $crumbs ) < 2 ) {
		return '';
	}
	$last = count( $crumbs ) - 1;
	$html = '<ol class="crumbs" aria-label="เส้นทางนำทาง">';
	foreach ( $crumbs as $i => $crumb ) {
		$link = '' !== (string) $crumb['url'] && ( $i < $last || 'done' === $hide_last );
		$html .= $link
			? '<li><a href="' . esc_url( $crumb['url'] ) . '">' . esc_html( $crumb['name'] ) . '</a></li>'
			: '<li' . ( $i === $last ? ' aria-current="page"' : '' ) . '>' . esc_html( $crumb['name'] ) . '</li>';
	}
	return $html . '</ol>';
}

/**
 * บรรทัดข้อมูลสั้นใต้คำโปรย (.phead__meta) จาก setting "ไอคอน | ข้อความ"
 */
function eab_pages_meta( $text, $vars = array() ) {
	$html = '';
	foreach ( eab_pages_rows( $text ) as $row ) {
		$label = isset( $row[1] ) ? $row[1] : $row[0];
		$icon  = isset( $row[1] ) ? $row[0] : 'info';
		if ( '' === $label ) {
			continue;
		}
		$html .= '<span>' . eab_icon( $icon ) . eab_pages_fmt( $label, $vars ) . '</span>';
	}
	return '' === $html ? '' : '<div class="phead__meta">' . $html . '</div>';
}

/**
 * กล่องสรุปด้านขวาของหัวเพจ (.sumbox)
 */
function eab_pages_sumbox( $title, $items, $note = '' ) {
	$title = trim( (string) $title );
	$lines = eab_lines( $items );
	if ( '' === $title || ! $lines ) {
		return '';
	}
	$html = '<aside class="sumbox" aria-label="' . esc_attr( $title ) . '"><h2>' . esc_html( $title ) . '</h2>';
	if ( 1 === count( $lines ) && false !== strpos( $lines[0], '>' ) ) {
		$parts = array_map( 'eab_pages_fmt', array_map( 'trim', explode( '>', $lines[0] ) ) );
		$html .= '<p class="flow">' . implode( ' ' . eab_icon( 'chevron-right' ) . ' ', $parts ) . '</p>';
	} else {
		$html .= '<ol>';
		foreach ( $lines as $i => $line ) {
			$html .= '<li><b>' . ( $i + 1 ) . '</b><span>' . eab_pages_fmt( $line ) . '</span></li>';
		}
		$html .= '</ol>';
	}
	if ( '' !== trim( (string) $note ) ) {
		$html .= '<p class="muted mt-16">' . eab_pages_fmt( $note ) . '</p>';
	}
	return $html . '</aside>';
}

/**
 * หัวเพจ .phead · ทุกช่อง *_html ต้อง escape มาแล้ว
 *
 * @param array $a {
 *     @type string $title     H1 (ข้อความล้วน)
 *     @type string $crumb     ชื่อหน้าใน breadcrumb ('' = ใช้ $title)
 *     @type bool   $crumb_cut ไม่แสดง crumb สุดท้าย (หน้าบทความ)
 *     @type string $lead      คำโปรย (รูปแบบ eab_pages_fmt)
 *     @type string $pre       HTML ก่อน H1 (ชิปหมวด)
 *     @type string $h1_class  คลาสของ H1
 *     @type string $mid       HTML ระหว่างคำโปรยกับบรรทัดข้อมูล (ช่องค้นหา)
 *     @type string $meta      HTML บรรทัดข้อมูล (eab_pages_meta)
 *     @type string $btns      HTML ปุ่ม (ห่อ .btns ให้)
 *     @type string $after     HTML ท้ายคอลัมน์ (ชิปหมวด รูปปก)
 *     @type string $sum       HTML กล่องสรุปด้านขวา (eab_pages_sumbox) · มี = แบ่งสองคอลัมน์
 * }
 */
function eab_pages_phead( $a ) {
	$a = wp_parse_args(
		$a,
		array(
			'title'     => '',
			'crumb'     => '',
			'crumb_cut' => false,
			'lead'      => '',
			'pre'       => '',
			'h1_class'  => '',
			'mid'       => '',
			'meta'      => '',
			'btns'      => '',
			'after'     => '',
			'sum'       => '',
		)
	);
	$title = wp_strip_all_tags( (string) $a['title'] );
	$crumb = '' !== (string) $a['crumb'] ? (string) $a['crumb'] : $title;
	$grid  = '' !== trim( (string) $a['sum'] );
	echo '<section class="phead"><div class="wrap">';
	echo eab_pages_crumbs_html( $crumb, (bool) $a['crumb_cut'] ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside
	if ( $grid ) {
		echo '<div class="phead__grid"><div>';
	}
	echo $a['pre']; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped by caller
	echo '<h1' . ( '' !== $a['h1_class'] ? ' class="' . esc_attr( $a['h1_class'] ) . '"' : '' ) . '>' . eab_text( $title ) . '</h1>'; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside eab_text
	if ( '' !== trim( (string) $a['lead'] ) ) {
		echo '<p class="lead">' . eab_pages_fmt( $a['lead'] ) . '</p>'; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside
	}
	echo $a['mid'] . $a['meta']; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped by caller
	if ( '' !== trim( (string) $a['btns'] ) ) {
		echo '<div class="btns">' . $a['btns'] . '</div>'; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped by caller
	}
	echo $a['after']; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped by caller
	if ( $grid ) {
		echo '</div>' . $a['sum'] . '</div>'; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped by caller
	}
	echo '</div></section>';
}

