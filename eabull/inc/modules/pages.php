	} elseif ( '' !== trim( (string) $shot ) ) {
		$icon  = isset( $row[1] ) ? $row[0] : 'file';
		$wait  = isset( $row[2] ) && '' !== $row[2] ? $row[2] : (string) eab_mod( 'pg_shot_wait' );
