 */
function eab_pages_shot( $img_key, $shot, $cap = '', $group = '' ) {
	$src  = eab_theme_asset_url( eab_mod( $img_key ) );
	$cap  = trim( (string) $cap );
	$html = '';
	$row  = array_map( 'trim', explode( '|', (string) $shot ) );
	$name = isset( $row[1] ) ? $row[1] : $row[0];
	if ( '' !== $src ) {
		$info  = eab_media_info( $src, 1280, 800 );
		$alt   = '' !== $name ? $name : $cap;
		$img   = '<img src="' . esc_url( $src ) . '" alt="' . esc_attr( $alt ) . '" width="' . esc_attr( (string) $info['width'] ) . '" height="' . esc_attr( (string) $info['height'] ) . '" loading="lazy" decoding="async">';
