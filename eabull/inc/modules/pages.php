/**
 * ประมวลผลเนื้อหาเพจปัจจุบันครั้งเดียว (สารบัญเก็บหัวข้อระหว่าง the_content)
 *
 * @return array { html, toc }
 */
function eab_pages_content() {
	static $cache = array();
	$id = (int) get_the_ID();
	if ( isset( $cache[ $id ] ) ) {
		return $cache[ $id ];
	}
	eab_pages_enable_table_cards();
	$GLOBALS['eab_toc'] = array();
	$html               = str_replace( ']]>', ']]&gt;', (string) apply_filters( 'the_content', get_the_content() ) );
	$cache[ $id ]       = array(
		'html' => $html,
		'toc'  => isset( $GLOBALS['eab_toc'] ) ? $GLOBALS['eab_toc'] : array(),
	);
	return $cache[ $id ];
}

