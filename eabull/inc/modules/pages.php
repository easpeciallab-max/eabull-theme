function eab_pages_has( $value ) {
	return ! eab_is_placeholder( $value );
}

/**
 * แทน {n} ในข้อความของ setting ด้วยตัวเลข
 */
function eab_pages_count_text( $key, $n ) {
	return str_replace( '{n}', number_format_i18n( (int) $n ), (string) eab_mod( $key ) );
}

/**
 * แตกบรรทัด "ซ้าย | ขวา" เป็น array( ซ้าย, ขวา )
 */
function eab_pages_pairs( $text ) {
	$out = array();
	foreach ( eab_lines( $text ) as $line ) {
		$parts = array_map( 'trim', explode( '|', $line, 2 ) );
		if ( '' === $parts[0] ) {
			continue;
		}
		$out[] = array( $parts[0], isset( $parts[1] ) ? $parts[1] : '' );
	}
	return $out;
}

/**
 * แตกบรรทัดเป็นช่อง (คั่นด้วย |) · ข้ามบรรทัดว่าง
 */
function eab_pages_rows( $text ) {
	$out = array();
	foreach ( eab_lines( $text ) as $line ) {
		$out[] = array_map( 'trim', explode( '|', $line ) );
	}
	return $out;
}

/**
 * ปลายทางของลิงก์ใน setting · '' = ไม่ลิงก์ (หน้าที่ยังเป็นฉบับร่าง หรือค่าว่าง)
 * รับ /slug/ · #id · URL เต็ม · mailto:… · คำพิเศษ mailto openchat facebook
 */
function eab_pages_url( $url ) {
	$url = trim( (string) $url );
	if ( '' === $url ) {
		return '';
	}
	$words = array(
		'mailto'   => '' !== trim( (string) eab_mod( 'contact_email' ) ) ? 'mailto:' . trim( (string) eab_mod( 'contact_email' ) ) : '',
		'openchat' => trim( (string) eab_mod( 'line_openchat_url' ) ),
		'facebook' => trim( (string) eab_mod( 'facebook_url' ) ),
	);
	if ( isset( $words[ $url ] ) ) {
		return $words[ $url ];
	}
	if ( '#' === $url[0] || preg_match( '#^(https?:)?//#i', $url ) || preg_match( '#^(mailto|tel):#i', $url ) ) {
		return $url;
	}
	$slug = (string) strtok( trim( $url, '/' ), '/?#' );
	if ( '' !== $slug && function_exists( 'eab_unreachable_slugs' ) && in_array( $slug, eab_unreachable_slugs(), true ) ) {
		return '';
	}
	return home_url( '/' . ltrim( $url, '/' ) );
}

/**
 * attribute ของลิงก์ภายนอก (แท็บใหม่ · ลิงก์พาร์ตเนอร์โบรกเกอร์ติด sponsored)
 */
function eab_pages_link_attrs( $href ) {
	if ( ! preg_match( '#^https?://#i', (string) $href ) ) {
		return '';
	}
	$host = (string) wp_parse_url( $href, PHP_URL_HOST );
	$home = (string) wp_parse_url( home_url( '/' ), PHP_URL_HOST );
	if ( '' !== $home && $host === $home ) {
		return '';
	}
	$rel = false !== stripos( $host, 'zaurix' ) ? 'sponsored noopener' : 'noopener';
	return ' target="_blank" rel="' . $rel . '"';
}

/**
 * ข้อความบรรทัดเดียวจาก setting → HTML ที่ escape แล้ว (รูปแบบดูหัวไฟล์)
 *
 * @param string $text ข้อความ
 * @param array  $vars ค่าแทน {key} เพิ่มเติม (ค่าเป็นข้อความธรรมดา)
 */
function eab_pages_fmt( $text, $vars = array() ) {
	$text = (string) $text;
	foreach ( (array) $vars as $key => $value ) {
		$text = str_replace( '{' . $key . '}', (string) $value, $text );
	}
	$html = esc_html( $text );
	$html = preg_replace_callback(
		'#\[([^\[\]\n]+)\]\(([^()\s]+)\)#u',
		function ( $m ) {
			$href = eab_pages_url( html_entity_decode( $m[2], ENT_QUOTES, 'UTF-8' ) );
			if ( '' === $href ) {
				return $m[1];
			}
			return '<a href="' . esc_url( $href ) . '"' . eab_pages_link_attrs( $href ) . '>' . $m[1] . '</a>';
		},
		$html
	);
	$html = preg_replace( '#\*\*(.+?)\*\*#u', '<b>$1</b>', $html );
	$html = preg_replace( '#`(.+?)`#u', '<span class="nocaps">$1</span>', $html );
	$email = trim( (string) eab_mod( 'contact_email' ) );
	$html  = str_replace( '{email}', '' !== $email ? '<span class="nocaps">' . esc_html( $email ) . '</span>' : eab_wait( '' ), $html );
	$html  = preg_replace_callback(
		'#\{wait(?::([^{}]+))?\}#u',
		function ( $m ) {
			return eab_wait( '', isset( $m[1] ) ? html_entity_decode( $m[1], ENT_QUOTES, 'UTF-8' ) : '' );
		},
		$html
	);
	return $html;
}

/**
 * ข้อความหลายบรรทัดจาก setting → บล็อก HTML (ย่อหน้า รายการ กล่องหมายเหตุ ลิงก์ลูกศร)
 */
function eab_pages_blocks( $text, $vars = array() ) {
	$html  = '';
	$type  = '';
	$items = array();
	$flush = function () use ( &$html, &$type, &$items ) {
		if ( ! $items ) {
			return;
		}
		$class = array(
			'-' => '',
			'+' => 'checks',
			'~' => 'checks checks--x',
		);
		$icon  = array(
			'-' => '',
			'+' => 'check',
			'~' => 'x',
		);
		$html .= '<ul' . ( '' !== $class[ $type ] ? ' class="' . $class[ $type ] . '"' : '' ) . '>';
		foreach ( $items as $item ) {
			$html .= '' === $icon[ $type ] ? '<li>' . $item . '</li>' : '<li>' . eab_icon( $icon[ $type ] ) . '<span>' . $item . '</span></li>';
		}
		$html .= '</ul>';
		$items = array();
		$type  = '';
	};
	foreach ( preg_split( '/\r\n|\r|\n/', (string) $text ) as $line ) {
		$line = trim( $line );
		if ( '' === $line ) {
			$flush();
			continue;
		}
		if ( preg_match( '/^([\-+~])\s+(.+)$/u', $line, $m ) ) {
			if ( $type !== $m[1] ) {
				$flush();
				$type = $m[1];
			}
			$items[] = eab_pages_fmt( $m[2], $vars );
			continue;
		}
		$flush();
		if ( preg_match( '/^\[(!|tip|i|ok)\]\s*(.+)$/u', $line, $m ) ) {
			$map   = array(
				'!'   => 'warn',
				'tip' => 'tip',
				'i'   => 'info',
				'ok'  => 'ok',
			);
			$html .= eab_pages_note( $map[ $m[1] ], $m[2], '', $vars );
		} elseif ( preg_match( '/^>\s*(.+?)\s*\|\s*(\S+)$/u', $line, $m ) ) {
			$html .= eab_pages_tlink( $m[1], $m[2] );
		} else {
			$html .= '<p>' . eab_pages_fmt( $line, $vars ) . '</p>';
		}
	}
	$flush();
	return $html;
}

