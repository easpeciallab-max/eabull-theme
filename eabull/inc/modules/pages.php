/**
 * หมวดบทความที่มีบทความเผยแพร่แล้ว (ชิปและการ์ดหมวด) · เรียงตาม eab_article_categories()
 *
 * @return array[] { name, url, count, slug, desc, current }
 */
function eab_pages_categories() {
	$order = function_exists( 'eab_article_categories' ) ? array_keys( eab_article_categories() ) : array();
	$terms = function_exists( 'get_terms' ) ? get_terms(
		array(
			'taxonomy'   => 'category',
			'hide_empty' => true,
		)
	) : array();
	if ( ! is_array( $terms ) ) {
		return array();
	}
	$current = is_category() ? (int) get_queried_object_id() : 0;
	$out     = array();
	foreach ( $terms as $term ) {
		if ( ! is_object( $term ) || ! (int) $term->count || 'uncategorized' === $term->slug ) {
			continue;
		}
		$out[] = array(
			'name'    => $term->name,
			'url'     => get_category_link( $term ),
			'count'   => (int) $term->count,
			'slug'    => $term->slug,
			'desc'    => trim( wp_strip_all_tags( (string) $term->description ) ),
			'current' => $current === (int) $term->term_id,
			'rank'    => false !== array_search( $term->slug, $order, true ) ? (int) array_search( $term->slug, $order, true ) : 99,
		);
	}
	usort(
		$out,
		function ( $x, $y ) {
			return $x['rank'] - $y['rank'];
		}
	);
	return $out;
}

