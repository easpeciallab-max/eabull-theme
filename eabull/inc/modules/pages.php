	return '<p class="note note--' . esc_attr( $type ) . ( '' !== $class ? ' ' . esc_attr( $class ) : '' ) . '">' . eab_icon( $icons[ $type ] ) . '<span>' . eab_pages_fmt( $text, $vars ) . '</span></p>';
}

/**
 * เรียกฟังก์ชันที่ echo แล้วคืนผลเป็นข้อความ (output buffer)
 */
function eab_pages_capture( $callback, ...$args ) {
	ob_start();
	call_user_func_array( $callback, $args );
	return (string) ob_get_clean();
}

