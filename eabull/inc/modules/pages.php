/**
 * ปุ่มจาก setting (บรรทัดละ 1 ปุ่ม: แบบ | ข้อความ | ลิงก์ | ไอคอน) · คืน HTML ของปุ่มทั้งหมด (ไม่มีกล่องห่อ)
 */
function eab_pages_btns( $text, $pos = 'content' ) {
	$allowed = array( 'primary', 'light', 'dark', 'outline', 'line', 'openchat', 'fb', 'sm', 'lg', 'block' );
	$html    = '';
	foreach ( eab_pages_rows( $text ) as $row ) {
		$words = array_values( array_intersect( preg_split( '/[\s+]+/', strtolower( $row[0] ) ), $allowed ) );
		$label = isset( $row[1] ) ? $row[1] : '';
		if ( ! $words || '' === $label ) {
			continue;
		}
		$mods = array_diff( $words, array( 'line' ) );
		$cls  = $mods ? implode( ' ', array_map( function ( $w ) { return 'btn--' . $w; }, $mods ) ) : '';
		if ( in_array( 'line', $words, true ) ) {
			$html .= eab_pages_line_btn( $label, $pos, $cls );
			continue;
		}
		$href = eab_pages_url( isset( $row[2] ) ? $row[2] : '' );
		if ( '' === $href ) {
			continue;
		}
		$icon = isset( $row[3] ) ? trim( $row[3] ) : '';
		if ( '' === $icon ) {
			$icon = in_array( 'openchat', $words, true ) ? 'users' : ( in_array( 'fb', $words, true ) ? 'facebook' : '' );
		}
		$inner = eab_pages_fmt( $label );
		if ( 'arrow' === $icon ) {
			$inner .= ' ' . eab_icon( 'arrow-right' );
		} elseif ( '' !== $icon ) {
			$inner = eab_icon( $icon ) . $inner;
		}
		$attrs = eab_pages_link_attrs( $href );
		if ( in_array( 'openchat', $words, true ) ) {
			$attrs .= ' data-line-pos="' . esc_attr( $pos . '-openchat' ) . '"';
		}
		$html .= '<a class="' . esc_attr( 'btn ' . $cls ) . '" href="' . esc_url( $href ) . '"' . $attrs . '>' . $inner . '</a>';
	}
	return $html;
}

