/**
 * เนื้อหาเพจในรูปแบบเอกสาร: band → .wrap.doclay → details.toc + article.doc.paper
 *
 * @param array $args {
 *     @type string|null $content  HTML ที่ผ่าน the_content แล้ว (null = เนื้อหาเพจปัจจุบัน)
 *     @type array       $toc      หัวข้อของ $content
 *     @type array       $extra    หัวข้อเพิ่มท้ายสารบัญ: array( array( 'id' => .., 'text' => .. ) )
 *     @type string      $label    aria-label ของ section
 *     @type string      $toc_label หัวกล่องสารบัญ
 *     @type string      $band     คลาสของ section
 *     @type string      $before   HTML ก่อนเนื้อหา · $after HTML ท้ายเนื้อหา (escape แล้ว)
 *     @type int         $min      มีหัวข้อถึงจำนวนนี้จึงพิมพ์สารบัญ
 *     @type bool        $date     ต่อท้ายด้วยวันที่ปรับปรุงล่าสุด
 * }
 */
function eab_pages_doclay( $args = array() ) {
	$a = wp_parse_args(
		$args,
		array(
			'content'   => null,
			'toc'       => array(),
			'extra'     => array(),
			'label'     => '',
			'toc_label' => '',
			'band'      => 'band band--alt',
			'before'    => '',
			'after'     => '',
			'min'       => 2,
			'date'      => false,
		)
	);
	if ( null === $a['content'] ) {
		$c            = eab_pages_content();
		$a['content'] = $c['html'];
		$a['toc']     = $c['toc'];
	}
	$content = (string) $a['content'];
	if ( '' === trim( wp_strip_all_tags( $content ) ) && '' === trim( (string) $a['before'] . $a['after'] ) ) {
		return;
	}
	$items = array_merge( eab_pages_toc_items( $a['toc'], $content ), (array) $a['extra'] );
	$toc   = count( $items ) >= (int) $a['min'] ? eab_pages_toc_html( $items, $a['toc_label'] ) : '';
	$date  = '';
	if ( $a['date'] && '' !== eab_pages_updated() ) {
		$date = '<p class="doc__date">' . esc_html( eab_mod( 'pg_updated_label' ) ) . ' <time datetime="' . esc_attr( get_the_modified_date( 'c' ) ) . '">' . esc_html( eab_pages_updated() ) . '</time></p>';
	}
	echo '<section class="' . esc_attr( $a['band'] ) . '"' . ( '' !== $a['label'] ? ' aria-label="' . esc_attr( $a['label'] ) . '"' : '' ) . '>';
	echo '<div class="wrap' . ( '' !== $toc ? ' doclay' : '' ) . '">' . $toc; // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside
	echo '<article class="doc paper' . ( '' === $toc ? ' doc--solo' : '' ) . '">' . $a['before'] . $content . $a['after'] . $date . '</article>'; // phpcs:ignore WordPress.Security.EscapeOutput -- the_content + escaped by caller
	echo '</div></section>';
}

