/**
 * ตาราง .tbl (มือถือเป็นการ์ด) จาก setting "ช่อง | ช่อง" · บรรทัดแรก = หัวตาราง · ช่องแรก = หัวแถว
 *
 * @param string $text ข้อความตาราง
 * @param array  $opt  { us: เลขคอลัมน์ที่ไฮไลต์ (1 = คอลัมน์ข้อมูลแรก, 0 = ไม่มี), vars: ค่าแทน {key} }
 */
function eab_pages_table( $text, $opt = array() ) {
	$opt  = wp_parse_args(
		$opt,
		array(
			'us'   => 0,
			'vars' => array(),
		)
	);
	$rows = eab_pages_rows( $text );
	if ( count( $rows ) < 2 ) {
		return '';
	}
	$head = array_map(
		function ( $c ) use ( $opt ) {
			return html_entity_decode( wp_strip_all_tags( eab_pages_fmt( $c, $opt['vars'] ) ), ENT_QUOTES, 'UTF-8' );
		},
		$rows[0]
	);
	$us   = (int) $opt['us'];
	$cell = function ( $value ) use ( $opt ) {
		$value = trim( (string) $value );
		foreach ( array( '✓' => array( 'y', 'check', 'pg_yes_label' ), '✗' => array( 'n', 'x', 'pg_no_label' ) ) as $mark => $yn ) {
			if ( 0 === strpos( $value, $mark ) ) {
				$rest = trim( substr( $value, strlen( $mark ) ) );
				$rest = '' !== $rest ? $rest : (string) eab_mod( $yn[2] );
				return '<span class="yn yn--' . $yn[0] . '">' . eab_icon( $yn[1] ) . '<span>' . eab_pages_fmt( $rest, $opt['vars'] ) . '</span></span>';
			}
		}
		return eab_pages_fmt( $value, $opt['vars'] );
	};
	$html = '<div class="tbl-wrap"><table class="tbl tbl--stack"><thead><tr>';
	foreach ( $head as $i => $h ) {
		$html .= '<th scope="col"' . ( $us && $i === $us ? ' class="us"' : '' ) . '>' . esc_html( $h ) . '</th>';
	}
	$html .= '</tr></thead><tbody>';
	foreach ( array_slice( $rows, 1 ) as $row ) {
		$html .= '<tr>';
		foreach ( $row as $i => $value ) {
			if ( 0 === $i ) {
				$html .= '<th scope="row">' . $cell( $value ) . '</th>';
				continue;
			}
			$label = isset( $head[ $i ] ) ? $head[ $i ] : '';
			$html .= '<td data-label="' . esc_attr( $label ) . '"' . ( $us && $i === $us ? ' class="us"' : '' ) . '>' . $cell( $value ) . '</td>';
		}
		$html .= '</tr>';
	}
	return $html . '</tbody></table></div>';
}

