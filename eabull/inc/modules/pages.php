/**
 * ลิงก์ข้อความพร้อมลูกศร (.tlink) · ปลายทางที่ยังเปิดไม่ได้ = ''
 */
function eab_pages_tlink( $label, $url, $icon = '', $pos = 'content' ) {
	if ( '' === trim( (string) $label ) ) {
		return '';
	}
	/* line = ปลายทางเดียวกับปุ่ม LINE (LINE OA → /go/ → แจ้งว่ารอข้อมูล) */
	if ( 'line' === trim( (string) $url ) ) {
		$target = eab_contact_target();
		$attrs  = ' data-line-pos="' . esc_attr( $pos ) . '"';
		if ( '' === $target['url'] ) {
			$href   = '#';
			$attrs .= ' data-wait="' . esc_attr( eab_mod( 'line_wait_text' ) ) . '"';
		} else {
			$href   = $target['url'];
			$attrs .= $target['is_line'] ? ' target="_blank" rel="noopener"' : '';
		}
		return '<a class="tlink" href="' . esc_url( $href ) . '"' . $attrs . '>' . eab_pages_fmt( $label ) . ' ' . eab_icon( '' !== $icon ? $icon : 'arrow-right' ) . '</a>';
	}
	$href = eab_pages_url( $url );
	if ( '' === $href ) {
		return '';
	}
	$attrs = eab_pages_link_attrs( $href );
	if ( '' === $icon ) {
		$icon = '' !== $attrs ? 'arrow-up-right' : 'arrow-right';
	}
	if ( 'openchat' === trim( (string) $url ) ) {
		$attrs .= ' data-line-pos="' . esc_attr( $pos . '-openchat' ) . '"';
	}
	return '<a class="tlink" href="' . esc_url( $href ) . '"' . $attrs . '>' . eab_pages_fmt( $label ) . ' ' . eab_icon( $icon ) . '</a>';
}

/**
 * กล่องหมายเหตุ .note
 *
 * @param string $type warn | info | tip | ok | bad
 */
function eab_pages_note( $type, $text, $class = '', $vars = array() ) {
	if ( '' === trim( (string) $text ) ) {
		return '';
	}
	$icons = array(
		'warn' => 'alert',
